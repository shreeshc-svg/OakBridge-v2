admin_router = APIRouter(
    prefix="/api/admin", tags=["admin-hampers"], dependencies=[Depends(require_admin)]
)


@admin_router.get("/hampers")
async def admin_list_hampers(q: str = "", enabled: str = "all"):
    query: dict[str, Any] = {"product_type": "hamper"}
    if enabled == "on":
        query["enabled"] = {"$ne": False}
    elif enabled == "off":
        query["enabled"] = False
    docs = await db.books.find(query, {"_id": 0}).sort("order", 1).to_list(None)
    needle = q.strip().lower()
    if needle:
        docs = [
            d for d in docs
            if needle in (d.get("title", "") + " " + (d.get("sku") or "")
                          + " " + (d.get("occasion") or "")).lower()
        ]
    out = []
    for d in docs:
        h = await _hydrate(d)
        # Surfaced so the list can warn before a box is oversold: 40 hampers
        # promising a title with 12 copies left is a packing problem discovered
        # at the worst possible moment.
        h["short_components"] = [
            i["label"] for i in h["hamper_items"]
            if i.get("is_book") and i.get("component_stock", 0) < d.get("stock", 0)
        ]
        out.append(h)
    return {"count": len(out), "hampers": out}


@admin_router.post("/hampers")
async def admin_create_hamper(payload: HamperCreate):
    doc = {
        "id": str(uuid.uuid4()),
        **payload.model_dump(),
        "product_type": "hamper",
        # Book-shaped fields the rest of the app still reads. A hamper has no
        # author, ISBN or page count; these keep every consumer that prints them
        # working without teaching each one about a new product type.
        "author": "",
        "isbn": "",
        "pages": 0,
        "category": "gifting",
        "subject": "Gifting",
        "created_at": datetime.now(timezone.utc).isoformat(),
    }
    await db.books.insert_one(dict(doc))
    log.info("Hamper created: %s (%s)", doc["title"], doc["id"])
    return await _hydrate({k: v for k, v in doc.items() if k != "_id"})


@admin_router.patch("/hampers/{hamper_id}")
async def admin_update_hamper(hamper_id: str, payload: HamperUpdate):
    updates = {k: v for k, v in payload.model_dump().items() if v is not None}
    if not updates:
        raise HTTPException(status_code=400, detail="Nothing to update")
    res = await db.books.update_one(
        {"id": hamper_id, "product_type": "hamper"}, {"$set": updates}
    )
    if res.matched_count == 0:
        raise HTTPException(status_code=404, detail="Hamper not found")
    doc = await db.books.find_one({"id": hamper_id}, {"_id": 0})
    return await _hydrate(doc)


@admin_router.delete("/hampers/{hamper_id}")
async def admin_delete_hamper(hamper_id: str):
    # Scoped to product_type so a mistyped id can never reach a book. Orders
    # keep their own snapshot of what was bought, so deleting a sold-out hamper
    # does not disturb anyone's receipt or packing slip.
    res = await db.books.delete_one({"id": hamper_id, "product_type": "hamper"})
    if res.deleted_count == 0:
        raise HTTPException(status_code=404, detail="Hamper not found")
    log.info("Hamper deleted: %s", hamper_id)
    return {"deleted": True, "id": hamper_id}


class ReorderRequest(BaseModel):
    ids: list


@admin_router.post("/hampers/reorder")
async def admin_reorder_hampers(payload: ReorderRequest):
    for i, hid in enumerate(payload.ids):
        await db.books.update_one(
            {"id": hid, "product_type": "hamper"}, {"$set": {"order": i}}
        )
    return {"ok": True, "count": len(payload.ids)}


@admin_router.get("/hampers-copy-defaults")
async def admin_copy_defaults():
    """So the admin form renders every editable string without a second copy of
    the list living in the frontend, drifting."""
    return {"copy": HAMPER_COPY_DEFAULTS, "page": GIFTING_PAGE_DEFAULTS,
            "banner": BANNER_DEFAULTS}
