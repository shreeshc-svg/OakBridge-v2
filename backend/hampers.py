def merge_copy(stored: Optional[dict]) -> dict:
    """Defaults, with the admin's saved strings on top. Blank means 'use default'."""
    out = dict(HAMPER_COPY_DEFAULTS)
    for k, v in (stored or {}).items():
        if v is None:
            continue
        # A string the admin has emptied falls back to the default rather than
        # rendering a blank label — an unlabelled field is worse than a generic
        # one, and "clear it to reset it" is the behaviour the docstring promises.
        if isinstance(v, str) and not v.strip():
            continue
        out[k] = v
    return out


def decorate_hamper(doc: dict) -> dict:
    """Fill in the copy for a hamper on its way out. No-op for a book."""
    if doc and doc.get("product_type") == "hamper":
        doc["hamper_copy"] = merge_copy(doc.get("hamper_copy"))
    return doc


