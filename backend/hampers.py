"""
Gift hampers: editable copy, the public listing, and admin SCRUD.

A hamper is a document in db.books with product_type="hamper" (see the note on
the Book model in server.py for why). This module owns the parts that are not
book-shaped: the wording on the page, which is entirely admin-editable, and the
create/read/update/delete screens behind it.

WHY EVERY STRING IS A FIELD
Marketing copy on a seasonal product changes between the mock-up and the
launch, and again the morning after. Hard-coding "What's inside" means a
one-line change, a commit, a review and a deploy to fix a typo on a page that
is live for eleven days. So every visible string is a key in `hamper_copy`,
defaulted here and overridable per hamper.

THE OVERRIDE TRAP
Defaults below apply only where the stored document has no value for that key.
Once a key has been saved from Admin -- even to the same string -- editing the
default here stops changing the live page, because the stored value wins. This
has caught us before on site content. To genuinely reset a key, clear it in
Admin; do not edit this file and expect the site to move.
"""
