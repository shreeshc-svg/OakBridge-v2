public_router = APIRouter(prefix="/api", tags=["hampers"])


async def _hydrate(doc: dict) -> dict:
    """Fill each contents line that points at a catalogue title.

    Cover, title, author and price are read live rather than copied in at build
    time, so a hamper cannot end up advertising last season's price for a book
    whose price moved. Only `value` is respected as an override, because the
    value of a title inside a bundle is an editorial choice, not the sale price.
    """
    doc = decorate_hamper(doc)
    ids = [i.get("book_id") for i in doc.get("hamper_items", []) if i.get("book_id")]
    books = {}
    if ids:
        rows = await db.books.find(
            {"id": {"$in": ids}},
            {"_id": 0, "id": 1, "title": 1, "author": 1, "cover_image": 1,
             "price": 1, "original_price": 1, "binding": 1, "stock": 1},
        ).to_list(None)
        books = {r["id"]: r for r in rows}

    out = []
    for item in doc.get("hamper_items", []):
        row = dict(item)
        src = books.get(item.get("book_id") or "")
        if src:
            row["label"] = src.get("title") or row.get("label") or ""
            row["note"] = row.get("note") or " · ".join(
                x for x in [src.get("author"), src.get("binding")] if x
            )
            row["image"] = src.get("cover_image") or ""
            row["is_book"] = True
            row["component_stock"] = src.get("stock", 0)
            if not row.get("value"):
                row["value"] = src.get("original_price") or src.get("price") or 0
        else:
            row["is_book"] = False
            # A line pointing at a title that has since been deleted would
            # otherwise render as a nameless empty row on a live sales page.
            if item.get("book_id") and not row.get("label"):
                row["label"] = "(this title is no longer in the catalogue)"
                row["missing"] = True
        out.append(row)
    doc["hamper_items"] = out
    doc["contents_value"] = sum(
        float(r.get("value") or 0) * int(r.get("qty", 1) or 1) for r in out
    )
    return doc


@public_router.get("/hampers")
async def list_hampers():
    docs = await db.books.find(
        {"product_type": "hamper", "enabled": {"$ne": False}}, {"_id": 0}
    ).sort("order", 1).to_list(None)
    return [await _hydrate(d) for d in docs]


@public_router.get("/hampers/{hamper_id}")
async def get_hamper(hamper_id: str):
    doc = await db.books.find_one(
        {"id": hamper_id, "product_type": "hamper"}, {"_id": 0}
    )
    if not doc:
        raise HTTPException(status_code=404, detail="Hamper not found")
    return await _hydrate(doc)


